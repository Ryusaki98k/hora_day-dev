-- 1. ตาราง customers (สร้างใหม่ถ้ายังไม่มี)
create table if not exists customers (
  id            bigint generated by default as identity primary key,
  full_name     text,
  nickname      text default '',
  birth_date    date not null,
  birth_time    time default '00:00:00',
  line_id       text,
  phone         text,
  province      text,
  address       text,
  notes         text default '',
  created_at    timestamptz default now(),
  updated_at    timestamptz default now(),
  last_consultation_date timestamptz,
  last_contact_at timestamptz,
  consent_given boolean,
  consent_at timestamptz,
  consent_note text,
  deleted_at timestamptz
);

-- 2. กรณีมีตาราง customers อยู่แล้ว ให้เพิ่มคอลัมน์ที่ขาดด้วย ADD COLUMN IF NOT EXISTS
alter table customers add column if not exists province text;
alter table customers add column if not exists last_consultation_date timestamptz;
alter table customers add column if not exists updated_at timestamptz default now();
alter table customers add column if not exists last_contact_at timestamptz;
alter table customers add column if not exists consent_given boolean;
alter table customers add column if not exists consent_at timestamptz;
alter table customers add column if not exists consent_note text;
alter table customers add column if not exists deleted_at timestamptz;

alter table customers alter column nickname drop not null;
alter table customers alter column birth_time drop not null;

-- 3. เปิด Realtime สำหรับตาราง customers
alter publication supabase_realtime add table customers;

-- 4. Row Level Security (RLS)
alter table customers enable row level security;
drop policy if exists "Allow all actions for anon" on customers;
create policy "Allow all actions for anon" on customers for all using (true) with check (true);

-- 5. ตารางประวัติการปรึกษา (consultation history)
create table if not exists consultations (
  id            bigint generated by default as identity primary key,
  customer_id   bigint not null references customers(id) on delete cascade,
  consultation_date timestamptz not null default now(),
  content       text,
  fee           numeric(10,2),
  notes         text,
  created_at    timestamptz default now()
);

alter publication supabase_realtime add table consultations;

alter table consultations enable row level security;
drop policy if exists "Allow all actions for consultations" on consultations;
create policy "Allow all actions for consultations" on consultations for all using (true) with check (true);

-- 6. ตารางแท็ก (Phase 1 เตรียมไว้ล่วงหน้า)
create table if not exists tags (
  id        bigint generated by default as identity primary key,
  name      text not null,
  color_key text default 'amber',
  created_at timestamptz default now()
);

alter publication supabase_realtime add table tags;
alter table tags enable row level security;
drop policy if exists "Allow all actions for anon" on tags;
create policy "Allow all actions for anon" on tags for all using (true) with check (true);

-- 7. ตารางความสัมพันธ์ลูกดวง-แท็ก (Phase 1)
create table if not exists client_tags (
  client_id bigint not null references customers(id) on delete cascade,
  tag_id    bigint not null references tags(id) on delete cascade,
  primary key (client_id, tag_id)
);

alter publication supabase_realtime add table client_tags;
alter table client_tags enable row level security;
drop policy if exists "Allow all actions for anon" on client_tags;
create policy "Allow all actions for anon" on client_tags for all using (true) with check (true);

-- 8. ฟังก์ชันสำหรับรัน SQL แบบ raw (สำหรับ migration runner)
create or replace function exec_sql(sql text)
returns void language plpgsql as $$
begin
  execute sql;
end;
$$;
